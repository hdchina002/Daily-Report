def daily_file(year=None):
    """每日数据文件 data/daily_YYYY.json（追加写，随仓库提交保存）。"""
    from datetime import datetime
    y = year or datetime.now().year
    return os.path.join(DATA_DIR, "daily_%d.json" % y)


# 把所有代码收集成集合，方便 fetcher 一次性批量拉取
def all_us_hk_a_codes():
    codes = set()
    for sec in SECTORS.values():
        for c, _, _ in sec:
            codes.add(c)
    for c, _ in US_INDICES + HK_INDICES + A_INDICES:
        codes.add(c)
    for sec in A_H_SECTORS.values():
        for c, _, _ in sec:
            codes.add(c)
    for c, _ in SOUTHBOUND_FOCUS:
        codes.add(c)
    return codes
